function scoreMatch(repo, keywords) {
  if (!keywords.length)
    return { hits: 0, coverage: 0 };
  const name = repo.full_name.toLowerCase();
  const desc = String(repo.description ?? "").toLowerCase();
  const topics = (repo.topics ?? []).map((t) => String(t).toLowerCase());
  let hits = 0;
  for (const kw of keywords) {
    const parts = kw.split(/[-_ ]/).filter((p) => p.length >= 3);
    const probe = [kw, ...parts];
    const found = probe.some((p) => name.includes(p) || desc.includes(p) || topics.some((t) => t.includes(p)));
    if (found)
      hits++;
  }
  return { hits, coverage: hits / keywords.length };
}
function tokenize(text) {
  return text.replace(/[\u200c\u200f\u200e]/g, " ").replace(/[^\p{L}\p{N}.+#/_-]+/gu, " ").split(/\s+/).map((t) => t.trim().toLowerCase()).filter(Boolean);
}
function extractKeywords(text, max = 6) {
  const out = [];
  const push = (w) => {
    const k = w.toLowerCase();
    if (!k || out.includes(k) || k.length < 2)
      return;
    out.push(k);
  };
  for (const tok of tokenize(text)) {
    if (LATIN.test(tok)) {
      if (tok.length >= 2 && !STOP.has(tok))
        push(tok);
      continue;
    }
    if (STOP.has(tok))
      continue;
    const exact = FA_TECH[tok];
    if (exact) {
      exact.forEach(push);
      continue;
    }
    const bare = tok.replace(/^(ال|بی|هم)/, "").replace(/(ها|های|هایی|ی|ات|ان)$/, "");
    const stripped = bare.length >= 3 ? bare : tok;
    const hit = FA_TECH[stripped] ?? FA_TECH[tok.replace(/(ها|های|هایی)$/, "")];
    if (hit) {
      hit.forEach(push);
      continue;
    }
    const key = Object.keys(FA_TECH).filter((k) => k.length >= 3 && tok.includes(k)).sort((a, b) => b.length - a.length)[0];
    if (key)
      FA_TECH[key].forEach(push);
  }
  return out.slice(0, max);
}
function searchLadder(text, opts = {}) {
  const kws = rankKeywords(extractKeywords(text, 8));
  const lang = opts.language ? ` language:${opts.language}` : "";
  const q = [];
  if (opts.aiQuery)
    q.push(opts.aiQuery);
  if (kws.length >= 3)
    q.push(`${kws.slice(0, 3).join(" ")}${lang}`);
  if (kws.length >= 2)
    q.push(`${kws.slice(0, 2).join(" ")}${lang}`);
  if (kws.length >= 2)
    q.push(`${kws.slice(0, 4).map((k) => `"${k}"`).join(" OR ")}${lang}`);
  if (kws.length) {
    q.push(`${kws[0]}${lang}`);
    q.push(`topic:${kws[0]}`);
    q.push(`${kws[0]}${lang} stars:>200`.trim());
  }
  return [...new Set(q.map((x) => x.trim()).filter((x) => x.length > 2))];
}
